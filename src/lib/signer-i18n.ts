export const DICTS: Record<Lang, Dict> = { pt, en, es, fr };

export function isLang(v: unknown): v is Lang {
  return v === "pt" || v === "en" || v === "es" || v === "fr";
}

/** Idioma do navegador, se for um dos suportados. */
export function browserLang(): Lang {
  const l = (typeof navigator !== "undefined" ? navigator.language : "pt").slice(0, 2).toLowerCase();
  return isLang(l) ? l : "pt";
}

export interface Translator {
  lang: Lang;
  t: (key: keyof Dict, vars?: Record<string, string | number>) => string;
  /** Igual a t(), mas os valores podem ser elementos React (ex.: <strong>). */
  tn: (key: keyof Dict, vars: Record<string, ReactNode>) => ReactNode;
  field: (type: FieldType) => string;
  /** Mensagem de erro traduzida a partir do código devolvido pelo servidor (ou o texto original). */
  error: (e: unknown) => string;
}

export function translator(lang: Lang): Translator {
  const d = DICTS[lang] ?? pt;
  const t = (key: keyof Dict, vars?: Record<string, string | number>) =>
    (d[key] ?? pt[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? `{${k}}`));
  const tn = (key: keyof Dict, vars: Record<string, ReactNode>) => {
    const parts = (d[key] ?? pt[key]).split(/(\{\w+\})/g);
    return createElement(Fragment, null, ...parts.map((p, i) => {
      const m = /^\{(\w+)\}$/.exec(p);
      return m ? createElement(Fragment, { key: i }, vars[m[1]]) : p;
    }));
  };
  const field = (type: FieldType) => d[`f_${type}` as keyof Dict] ?? type;
  const error = (e: unknown) => {
    const err = e as { code?: string; status?: number; message?: string };
    if (err?.status === 0) return d.e_network;
    const key = `e_${err?.code ?? ""}` as keyof Dict;
    if (err?.code && key in d) return d[key];
    return err?.message ?? String(e);
  };
  return { lang, t, tn, field, error };
}

export const I18n = createContext<Translator>(translator("pt"));
export const useT = () => useContext(I18n);
